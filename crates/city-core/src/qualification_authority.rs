fn fail(_: impl std::fmt::Debug)->TxError {TxError::InvalidOperation}
fn rule(error:q::Error)->TxError {if error==q::Error::Capacity {TxError::WorkingLimit} else {fail(error)}}
pub(crate) fn id(value:u64)->[u8;16] {let mut out=[0;16];out[8..].copy_from_slice(&value.to_be_bytes());out}
fn original_id(value:[u8;16])->Result<u64,TxError> {
    if value[..8]!=[0;8] {return Err(TxError::InvalidOperation);}
    let number=u64::from_be_bytes(value[8..].try_into().map_err(fail)?);
    if number==0 {return Err(TxError::InvalidOperation);} Ok(number)
}
struct Sink { hash:Sha256, used:usize, limit:usize }
impl Write for Sink {
    fn write(&mut self, bytes:&[u8])->std::io::Result<usize> {
        self.used=self.used.checked_add(bytes.len()).filter(|n|*n<=self.limit)
            .ok_or_else(||std::io::Error::other("qualification_auth_bytes"))?;
        self.hash.update(bytes);Ok(bytes.len())
    }
    fn flush(&mut self)->std::io::Result<()> {Ok(())}
}
fn digest(value:&impl Serialize,domain:&[u8],limit:usize)->Result<[u8;32],TxError> {
    let mut sink=Sink{hash:Sha256::new(),used:0,limit};sink.hash.update(domain);
    serde_json::to_writer(&mut sink,value).map_err(fail)?;Ok(sink.hash.finalize().into())
}
